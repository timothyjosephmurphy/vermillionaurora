import {writeFile} from 'node:fs/promises';
import {products,catalogVersion,validateCatalog} from '../catalog/catalog.mjs';
import {deriveParcel} from '../catalog/shipping.mjs';
validateCatalog();
const checkout={},inventory={},legacyLinks={};
for(const p of products) {
 if(p.type==='painting')inventory[p.id]={status:p.listing.status};
 if(p.checkout?.mode==='paypal-link')legacyLinks[p.id]=p.checkout.link;
 if(p.checkout?.mode!=='integrated')continue;
 const s=p.checkout.shipping,rollable=!(p.framing&&!/unframed/i.test(p.framing));
 const pkg=s.packageOverride?{length:s.length,width:s.width,height:s.height,weight:s.weight,packaging:s.packaging}:deriveParcel(p.dimensions,s.weight,s.height,{rollable});
 checkout[p.id]={title:p.title,amount:p.listing.price.amount,currency:p.listing.price.currency,parcel:{length:pkg.length,width:pkg.width,height:pkg.height,weight:pkg.weight},packaging:pkg.packaging,...(s.insuranceRequested?{insuranceRequested:true}:{}),...(p.listing.status!=='available'?{available:false}:{})};
}
await writeFile(new URL('../cloudflare/checkout-catalog.mjs',import.meta.url),`// Generated by npm run build from catalog/products.json. Do not edit.\nexport const catalogVersion = ${JSON.stringify(catalogVersion)};\nexport const inventory = ${JSON.stringify(inventory,null,2)};\nexport const legacyLinks = ${JSON.stringify(legacyLinks,null,2)};\nexport default ${JSON.stringify(checkout,null,2)};\n`);
// Commission deposits: 50% of each fixed-price commission package. Non-shippable service lines;
// the balance is invoiced before the finished work ships. Server-owned prices, never from the browser.
const deposits={};
for(const p of products) {
 const price=p.listing?.price;
 if(p.type!=='commission'||!price||price.from||price.currency!=='USD'||!/^\d+\.\d{2}$/.test(price.amount))continue;
 const cents=Number(price.amount.replace('.',''));if(!cents||cents%2)throw Error(`${p.id} deposit must split evenly to the cent`);
 deposits[`deposit-${p.id}`]={type:'deposit',package:p.id,title:`Commission deposit – ${p.title} (50%)`,packageTitle:p.title,packagePrice:price.amount,amount:(cents/200).toFixed(2),currency:'USD'};
}
await writeFile(new URL('../cloudflare/commission-deposits.mjs',import.meta.url),`// Generated by npm run build from catalog/products.json. Do not edit.\nexport default ${JSON.stringify(deposits,null,2)};\n`);
console.log(`Built ${Object.keys(deposits).length} commission deposits`);
console.log(`Built ${Object.keys(checkout).length} checkout products; catalog ${catalogVersion}`);
