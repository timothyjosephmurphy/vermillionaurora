import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {
  bindingAccesses,
  checkWorkerTree,
  configBindingNames,
  envBindingNames,
  missingConfigBindings,
  parseJsonc,
  unknownInFile,
} from '../scripts/check-worker-bindings.mjs';

const site = envBindingNames('tsconfig.site.json', 'SiteEnv');
const checkout = envBindingNames('tsconfig.checkout.json', 'CheckoutEnv');

test('tsconfig projects and the typecheck script stay wired', () => {
  const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
  assert.match(pkg.scripts.typecheck, /tsc -p tsconfig\.site\.json --noEmit/);
  assert.match(pkg.scripts.typecheck, /tsc -p tsconfig\.checkout\.json --noEmit/);
  assert.match(pkg.scripts.typecheck, /scripts\/check-worker-bindings\.mjs/);
  assert.equal(pkg.devDependencies.typescript, '5.9.3');
  assert.equal(pkg.devDependencies.wrangler, '4.143.0');
  const root = parseJsonc(fs.readFileSync('tsconfig.json', 'utf8'));
  assert.deepEqual(root.references.map(ref => ref.path), ['./tsconfig.site.json', './tsconfig.checkout.json']);
  const siteConfig = parseJsonc(fs.readFileSync('tsconfig.site.json', 'utf8'));
  const checkoutConfig = parseJsonc(fs.readFileSync('tsconfig.checkout.json', 'utf8'));
  assert.equal(siteConfig.compilerOptions.noEmit, true);
  assert.equal(siteConfig.compilerOptions.checkJs, true);
  assert.equal(checkoutConfig.compilerOptions.noEmit, true);
  assert.match(fs.readFileSync('cloudflare/commission-worker.js', 'utf8'), /^\/\/ @ts-check/m);
  const gate = fs.readFileSync('.github/workflows/release-gate.yml', 'utf8');
  assert.match(gate, /name: Typecheck Worker bindings[\s\S]*run: npm run typecheck/);
  const unit = gate.slice(gate.indexOf('  unit-and-print:'), gate.indexOf('  browser-chromium:'));
  assert.match(unit, /npm run typecheck/);
});

test('generated Env types cover wrangler bindings and secret augmentations', () => {
  for (const name of ['ASSETS', 'CATALOG_DB', 'CHECKOUT', 'IMAGES', 'PRIMARY_HOST', 'LEGACY_REDIRECT', 'CATALOG_ADMIN_PASSWORD', 'HEX_FETCH']) {
    assert.equal(site.has(name), true, name);
  }
  for (const name of ['ASSETS', 'CATALOG_DB', 'COMMISSION_UPLOADS', 'SALES_ARCHIVE', 'IMAGES', 'PAINTING_STOCK', 'SALES_LEDGER', 'BITCOIN_ORDERS', 'CART_ORDERS', 'QUICKBOOKS', 'NEURAL_DANCE_DEBUG', 'SQUARE_ACCESS_TOKEN', 'BTCPAY_API_KEY', 'BTCPAY_STORE_ID', 'BTCPAY_WEBHOOK_SECRET', 'FINERWORKS_APP_KEY', 'FINERWORKS_PAYMENT_TOKEN', 'FINERWORKS_WEB_API_KEY', 'SHIPPO_TOKEN', 'RPI_API_KEY', 'CATALOG_ADMIN_PASSWORD', 'TESTIMONIAL_REPLY_ADDRESS']) {
    assert.equal(checkout.has(name), true, name);
  }
  assert.equal(site.has('ORDER_COORDINATOR'), false);
  assert.equal(checkout.has('ORDER_COORDINATOR'), false);
  assert.deepEqual(missingConfigBindings('wrangler.jsonc', site), []);
  assert.deepEqual(missingConfigBindings('cloudflare/wrangler.jsonc', checkout), []);
  const siteConfig = parseJsonc(fs.readFileSync('wrangler.jsonc', 'utf8'));
  const checkoutConfig = parseJsonc(fs.readFileSync('cloudflare/wrangler.jsonc', 'utf8'));
  assert.equal(configBindingNames(siteConfig).has('CHECKOUT'), true);
  assert.equal(configBindingNames(checkoutConfig).has('CART_ORDERS'), true);
  assert.match(fs.readFileSync('worker-configuration.d.ts', 'utf8'), /Generated by Wrangler/);
  assert.match(fs.readFileSync('cloudflare/worker-configuration.d.ts', 'utf8'), /Generated by Wrangler/);
  assert.match(fs.readFileSync('worker-configuration.d.ts', 'utf8'), /interface SiteEnv/);
  assert.match(fs.readFileSync('cloudflare/worker-configuration.d.ts', 'utf8'), /interface CheckoutEnv/);
});

test('env binding typos are reported and the workers only use declared names', () => {
  assert.deepEqual(unknownInFile('export function f(env){ return env.ORDER_COORDINATOR; }', site), ['ORDER_COORDINATOR']);
  assert.deepEqual(unknownInFile('export function f(env){ return env.CHECKOUT.fetch(env.CATALOG_DB); }', site), []);
  assert.deepEqual([...bindingAccesses('const {SHIPPO_TOKEN} = env; env?.BTCPAY_API_KEY; this.env.CART_ORDERS;')].sort(), ['BTCPAY_API_KEY', 'CART_ORDERS', 'SHIPPO_TOKEN']);
  assert.deepEqual(checkWorkerTree('worker', site), []);
  assert.deepEqual(checkWorkerTree('cloudflare', checkout), []);
});
