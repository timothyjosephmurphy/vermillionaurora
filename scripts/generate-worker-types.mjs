// Regenerates the two Wrangler declaration files. They are gitignored; typecheck
// and the unit runner call this so CI and local checks do not depend on a commit.
import {spawnSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseJsonc} from './check-worker-bindings.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const wrangler = path.join(root, 'node_modules', 'wrangler', 'bin', 'wrangler.js');

// `wrangler types` runs wrangler.jsonc's build command, which is a full site
// build and refuses to run without print-master bytes. Bindings do not depend
// on that build. Typegen reads a copy with the build command removed.
function configForTypes(sourceRel) {
  const source = path.join(root, sourceRel);
  const config = parseJsonc(fs.readFileSync(source, 'utf8'));
  delete config.build;
  const dest = path.join(root, '.cache', 'worker-types', sourceRel);
  fs.mkdirSync(path.dirname(dest), {recursive: true});
  fs.writeFileSync(dest, JSON.stringify(config));
  return path.relative(root, dest);
}

const jobs = [
  ['types', `--config=${configForTypes('wrangler.jsonc')}`, '--env-interface=SiteEnv', 'worker-configuration.d.ts'],
  ['types', `--config=${configForTypes('cloudflare/wrangler.jsonc')}`, '--env-interface=CheckoutEnv', 'cloudflare/worker-configuration.d.ts'],
];

for (const args of jobs) {
  const out = path.join(root, args.at(-1));
  const result = spawnSync(process.execPath, [wrangler, ...args], {
    cwd: root,
    encoding: 'utf8',
    env: {...process.env, WRANGLER_SEND_METRICS: 'false'},
  });
  if (result.status !== 0) {
    if (result.stdout) process.stdout.write(result.stdout);
    if (result.stderr) process.stderr.write(result.stderr);
    process.exit(result.status || 1);
  }
  const text = fs.readFileSync(out, 'utf8');
  if (!/Generated by Wrangler/.test(text)) {
    console.error(`wrangler types did not write a generated header: ${args.at(-1)}`);
    process.exit(1);
  }
  // Binding names belong in these files. Credential values must not.
  if (/-----BEGIN |sk_live_|AKIA[0-9A-Z]{16}/.test(text)) {
    console.error(`refusing to keep ${args.at(-1)}: it contains a credential value`);
    fs.rmSync(out, {force: true});
    process.exit(1);
  }
  console.log(`generated ${args.at(-1)}`);
}
